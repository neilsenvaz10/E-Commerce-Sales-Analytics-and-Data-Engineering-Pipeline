-- Minimal Snowflake setup for the college microproject. NOT RUN YET (no Snowflake account exists).
-- Run once as ACCOUNTADMIN in a Snowsight worksheet ("Run all").
-- Before running, replace the three <...PUBLIC_KEY> placeholders with the BODY of each public
-- key: the base64 text without the BEGIN/END lines, on one line. Never paste a PRIVATE key here.
--
-- NOTE (comments only; the SQL below is unchanged): Airbyte Cloud could not sync because of a
-- credit restriction, so a Python loader (ingestion/load_sample_to_snowflake.py) now writes RAW.
-- It reuses AIRBYTE_USER / AIRBYTE_ROLE and the "airbyte" key; those names are historical.
--
-- Layout:  database ECOMMERCE_ANALYTICS
--            RAW             written by the Python loader (role AIRBYTE_ROLE, historical name)
--            AIRBYTE_INTERNAL was Airbyte's internal schema; unused now, harmless (role AIRBYTE_ROLE)
--            STAGING         dbt view  stg_online_retail (role TRANSFORM_ROLE)
--            ANALYTICS       dbt table fct_sales         (role TRANSFORM_ROLE, read by READER_ROLE)

-- 1. Roles ---------------------------------------------------------------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS AIRBYTE_ROLE;    -- (historical name) the Python loader: writes RAW only
CREATE ROLE IF NOT EXISTS TRANSFORM_ROLE;  -- dbt and Airflow: reads RAW, writes STAGING and ANALYTICS
CREATE ROLE IF NOT EXISTS READER_ROLE;     -- Streamlit: read-only on ANALYTICS
GRANT ROLE AIRBYTE_ROLE   TO ROLE SYSADMIN;
GRANT ROLE TRANSFORM_ROLE TO ROLE SYSADMIN;
GRANT ROLE READER_ROLE    TO ROLE SYSADMIN;

-- 2. Warehouse (smallest size, suspends after 60 seconds idle) and database ---------
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS ECOMMERCE_WH
  WAREHOUSE_SIZE = 'XSMALL' WAREHOUSE_TYPE = 'STANDARD'
  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS ECOMMERCE_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_ANALYTICS.RAW;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_ANALYTICS.AIRBYTE_INTERNAL;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_ANALYTICS.ANALYTICS;

-- Schema ownership (Airbyte needs to own its two schemas; dbt owns its two)
GRANT OWNERSHIP ON SCHEMA ECOMMERCE_ANALYTICS.RAW              TO ROLE AIRBYTE_ROLE   COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ECOMMERCE_ANALYTICS.AIRBYTE_INTERNAL TO ROLE AIRBYTE_ROLE   COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ECOMMERCE_ANALYTICS.STAGING          TO ROLE TRANSFORM_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ECOMMERCE_ANALYTICS.ANALYTICS        TO ROLE TRANSFORM_ROLE COPY CURRENT GRANTS;

-- 3. Grants ----------------------------------------------------------------------
USE ROLE SECURITYADMIN;
GRANT USAGE ON WAREHOUSE ECOMMERCE_WH TO ROLE AIRBYTE_ROLE;
GRANT USAGE ON WAREHOUSE ECOMMERCE_WH TO ROLE TRANSFORM_ROLE;
GRANT USAGE ON WAREHOUSE ECOMMERCE_WH TO ROLE READER_ROLE;
GRANT USAGE ON DATABASE ECOMMERCE_ANALYTICS TO ROLE AIRBYTE_ROLE;
GRANT USAGE ON DATABASE ECOMMERCE_ANALYTICS TO ROLE TRANSFORM_ROLE;
GRANT USAGE ON DATABASE ECOMMERCE_ANALYTICS TO ROLE READER_ROLE;

-- dbt reads what Airbyte writes (tables are recreated on every Full Refresh Overwrite sync,
-- so grant on future tables as well)
GRANT USAGE ON SCHEMA ECOMMERCE_ANALYTICS.RAW TO ROLE TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA ECOMMERCE_ANALYTICS.RAW TO ROLE TRANSFORM_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ECOMMERCE_ANALYTICS.RAW TO ROLE TRANSFORM_ROLE;

-- Streamlit reads the final tables and views only
GRANT USAGE ON SCHEMA ECOMMERCE_ANALYTICS.ANALYTICS TO ROLE READER_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA ECOMMERCE_ANALYTICS.ANALYTICS TO ROLE READER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ECOMMERCE_ANALYTICS.ANALYTICS TO ROLE READER_ROLE;
GRANT SELECT ON ALL VIEWS     IN SCHEMA ECOMMERCE_ANALYTICS.ANALYTICS TO ROLE READER_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ECOMMERCE_ANALYTICS.ANALYTICS TO ROLE READER_ROLE;

-- 4. Service users (key-pair login only, no password) -----------------------------
CREATE USER IF NOT EXISTS AIRBYTE_USER TYPE = SERVICE
  DEFAULT_ROLE = AIRBYTE_ROLE DEFAULT_WAREHOUSE = ECOMMERCE_WH;
CREATE USER IF NOT EXISTS TRANSFORM_USER TYPE = SERVICE
  DEFAULT_ROLE = TRANSFORM_ROLE DEFAULT_WAREHOUSE = ECOMMERCE_WH;
CREATE USER IF NOT EXISTS READER_USER TYPE = SERVICE
  DEFAULT_ROLE = READER_ROLE DEFAULT_WAREHOUSE = ECOMMERCE_WH;

ALTER USER AIRBYTE_USER   SET RSA_PUBLIC_KEY = '<AIRBYTE_PUBLIC_KEY>';
ALTER USER TRANSFORM_USER SET RSA_PUBLIC_KEY = '<TRANSFORM_PUBLIC_KEY>';
ALTER USER READER_USER    SET RSA_PUBLIC_KEY = '<READER_PUBLIC_KEY>';

GRANT ROLE AIRBYTE_ROLE   TO USER AIRBYTE_USER;
GRANT ROLE TRANSFORM_ROLE TO USER TRANSFORM_USER;
GRANT ROLE READER_ROLE    TO USER READER_USER;

